let a = 5;
let b = 2;
let resultado1 = a++ + b;

console.log("Primer caso:");
console.log("resultado1 =", resultado1);
console.log("a =", a);

// Segundo caso: preincremento
let c = 5;
let d = 2;
let resultado2 = ++c + d;

console.log("Segundo caso:");
console.log("resultado2 =", resultado2);
console.log("c =", c);
